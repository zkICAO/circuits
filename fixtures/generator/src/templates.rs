//! Writes an input template beside every circuit.
//!
//! A circuit's witness file is not committed, because a real one holds a
//! holder's document. What is committed is a template with the same field
//! names and a placeholder in every value, so someone who clones this
//! repository can see exactly what a circuit expects and where their own
//! material goes, without a fixture standing in for it.
//!
//! Generated from the compiled ABI rather than written by hand, so a
//! circuit whose inputs change cannot leave a template describing the old
//! ones.

use std::fmt::Write as _;
use std::path::Path;

use crate::manifest;

const HEADER: &str = "\
# Generated by fixtures/generator with the templates subcommand. Do not edit.
#
# Copy this to Prover.toml and replace every placeholder with your own
# material. Nothing here is a working value: a witness holds one holder's
# document, so no real one is committed anywhere in this repository.
#
# Where a value comes from is written beside it. The witness tools under
# tools/ derive the ones that are hashes of something else, so that they are
# computed by the same library the circuit checks them against.
";

