pub fn write(circuits_root: &Path) {
    let mut written = 0;

    for package in manifest::circuit_packages(circuits_root) {
        let bytecode = circuits_root.join(format!("target/{}.json", package.name));

        assert!(
            bytecode.exists(),
            "{} has not been compiled; run nargo compile first",
            package.name
        );

        let mut body = String::from(HEADER);

        for parameter in manifest::parameters(&bytecode) {
            body.push('\n');

            if let Some(note) = note(&parameter.name) {
                writeln!(body, "# {note}").unwrap();
            }

            writeln!(body, "{} = {}", parameter.name, placeholder(&parameter)).unwrap();
        }

        let destination = circuits_root
            .join(&package.directory)
            .join("Prover.toml.example");

        std::fs::write(&destination, body).expect("cannot write an input template");

        written += 1;
    }

    println!("wrote {written} input templates");
}

fn note(name: &str) -> Option<String> {
    if let Some((_, source)) = FROM_TOOL
        .iter()
        .filter(|(key, _)| name == *key || name.ends_with(&format!("_{key}")))
        .max_by_key(|(key, _)| key.len())
    {
        return Some(format!("from {source}"));
    }

    GUIDANCE
        .iter()
        .filter(|(key, _)| name == *key || name.ends_with(&format!("_{key}")))
        .max_by_key(|(key, _)| key.len())
        .map(|(_, text)| (*text).to_string())
}

/// A placeholder that names what is missing and cannot be mistaken for a
/// value: every element says so, and a witness built from this file fails
/// to parse rather than proving something meaningless.
fn placeholder(parameter: &manifest::Parameter) -> String {
    let scalar = format!("\"<your {}>\"", parameter.name.replace('_', " "));

    match parameter.length {
        None => scalar,
        Some(length) if length <= 4 => {
            let elements = vec![scalar; length];

            format!("[{}]", elements.join(", "))
        }
        Some(length) => format!("[{scalar}, {scalar}, \"...\"]  # {length} elements in total"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_placeholder_says_what_is_missing() {
        let scalar = placeholder(&manifest::Parameter {
            name: "session_salt".to_string(),
            length: None,
        });

        assert_eq!(scalar, "\"<your session salt>\"");

        let short = placeholder(&manifest::Parameter {
            name: "data".to_string(),
            length: Some(4),
        });

        assert_eq!(short.matches("<your data>").count(), 4);

        // A long array is elided rather than repeated five hundred times,
        // and says how many elements it really takes.
        let long = placeholder(&manifest::Parameter {
            name: "proof".to_string(),
            length: Some(500),
        });

        assert!(long.contains("500 elements in total"));
    }

    // A placeholder that could be mistaken for a value would be worse than
    // none, so no template line may parse as a number or a hex literal.
    #[test]
    fn no_placeholder_looks_like_a_value() {
        for name in ["domain", "commitment", "signature_r"] {
            let text = placeholder(&manifest::Parameter {
                name: name.to_string(),
                length: None,
            });

            assert!(text.contains("<your"), "{name} placeholder is not marked");

            assert!(
                text.trim_matches('"').parse::<u128>().is_err(),
                "{name} placeholder parses as a number"
            );
        }
    }

    // The reason a template exists at all: production source and fixture
    // material have to stay apart. Nargo has no dev-dependencies section and
    // no separate test file, so the rule is positional: every reference to
    // the fixtures sits below the first test in its file, and the helpers
    // that read them sit at the bottom under a banner saying so.
    //
    // This is what actually keeps fixtures out of a compiled circuit, since
    // Noir does not compile test items into main. It is checked here rather
    // than by searching the artifact: the executable half of a compiled
    // circuit is gzipped, and the source map beside it holds every source
    // file by design, so searching the artifact answers a different
    // question than the one that matters.
    #[test]
    fn fixtures_are_referenced_only_below_the_tests() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(|p| p.parent())
            .expect("unexpected generator location");

        let mut checked = 0;

        for directory in ["lib", "bin"] {
            for source in walk(&root.join(directory)) {
                if source.to_string_lossy().contains("testdata") {
                    continue;
                }

                let text = std::fs::read_to_string(&source).expect("cannot read a source file");

                let Some(use_at) = text.find("testdata::") else {
                    continue;
                };

                let first_test = text.find("#[test").unwrap_or(usize::MAX);

                assert!(
                    use_at > first_test,
                    "{} reads the fixtures above its first test",
                    source.display()
                );

                checked += 1;
            }
        }

        assert!(
            checked > 0,
            "no package reads the fixtures, which cannot be right"
        );
    }

    fn walk(directory: &Path) -> Vec<std::path::PathBuf> {
        let mut found = Vec::new();

        let Ok(entries) = std::fs::read_dir(directory) else {
            return found;
        };

        for entry in entries.flatten() {
            let path = entry.path();

            if path.is_dir() {
                found.extend(walk(&path));
            } else if path.extension().is_some_and(|e| e == "nr") {
                found.push(path);
            }
        }

        found
    }

    #[test]
    fn a_name_takes_the_most_specific_note() {
        // Both "salt" and "session_salt" have guidance; the longer key wins.
        let session = note("session_salt").expect("session_salt has a note");

        assert!(session.contains("keep it to open this commitment later"));

        // A tool sourced name says which tool rather than describing itself.
        assert_eq!(
            note("secret").as_deref(),
            Some("from tools/document_secret")
        );
    }
}
